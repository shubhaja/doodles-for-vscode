const {test}=require('node:test'),assert=require('node:assert/strict');
const {session}=require('../goldfish/test-dom.cjs');
test('lids move progressively and reverse without replacing the visible eye',()=>{
  const s=session();
  s.context.MutationObserver=class {observe(){}disconnect(){}};
  s.load('../terminal/terminal-eyes.js');
  const button=s.document.querySelector('#doodles-mode-god');
  const overlay=s.document.querySelector('.doodles-eyes-overlay');
  const clip=s.document.querySelector('clipPath').children[0];
  const aperture=()=>Number(clip.getAttribute('transform').match(/scale\(1 ([^)]+)\)/)[1]);
  button.click();assert.equal(aperture(),0);
  s.advance(240);assert.ok(aperture()>0 && aperture()<1);
  s.advance(260);assert.equal(aperture(),1);
  button.click();assert.equal(overlay.hidden,false);
  s.advance(140);const partial=aperture(),shape=clip.getAttribute('d');
  assert.ok(partial>0 && partial<1);
  button.click();assert.equal(aperture(),partial);
  assert.equal(clip.getAttribute('d'),shape);
  s.advance(500);assert.equal(aperture(),1);assert.equal(overlay.hidden,false);
  button.click();s.advance(320);assert.equal(aperture(),0);assert.equal(overlay.hidden,true);
  button.click();s.advance(80);s.event(s.window,'pagehide');s.advance(600);
  assert.equal(s.document.querySelector('.doodles-eyes-overlay'),null);
});
