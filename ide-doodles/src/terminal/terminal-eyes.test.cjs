test('flat eyes leave the surface intact; pupils track and stay bounded',()=>{
  const s=session();
  s.context.Math=Object.create(Math);s.context.Math.random=()=>.999999;
  s.context.MutationObserver=class {observe(){}disconnect(){}};
  const create=s.document.createElement;
  const surface=create('main');surface.className='monaco-workbench';
  surface.getBoundingClientRect=()=>({left:0,top:0,width:600,height:400});
  surface.style.setProperty('filter','contrast(.9)');surface.style.getPropertyPriority=()=> 'important';
  s.context.getComputedStyle=el=>({filter:el.style.getPropertyValue('filter')});
  s.document.body.append(surface);s.load('../terminal/terminal-eyes.js');
  const openings=s.document.querySelectorAll('.doodles-eye-opening');
  assert.equal(new Set(openings.map(el=>el.style.cssText)).size,10,'eyes have distinct placement and dimensions');
  const clips=s.document.querySelectorAll('clipPath');
  assert.equal(new Set(clips.map(el=>el.children[0].getAttribute('d'))).size,10,'eyes have different silhouettes');
  openings.forEach((el,i)=>{el.getBoundingClientRect=()=>({left:i?2000:152,top:76,width:96,height:48});});
  const button=s.document.querySelector('#doodles-mode-god');button.click();s.advance(700);
  assert.equal(surface.style.filter,'contrast(.9)','opening eyes does not distort the surface');
  assert.equal(s.document.querySelectorAll('filter').length,0,'no screen-warp filter');
  assert.ok(clips.every(clip=>clip.children[0].getAttribute('transform').includes('scale(1 1)')),'eye outlines finish fully open');
  s.event(s.window,'pointermove',{clientX:900,clientY:100});s.advance(20);
  const pupil=s.document.querySelectorAll('g').find(el=>el.getAttribute('class')==='doodles-eye-pupil');
  function assertGaze(dx,dy){
    const [x,y]=pupil.getAttribute('transform').match(/-?\d+/g).map(Number);
    const angle=Number(pupil.parentNode.parentNode.parentNode.getAttribute('transform').match(/-?[\d.]+/)[0])*Math.PI/180;
    const screenX=x*Math.cos(angle)-y*Math.sin(angle),screenY=x*Math.sin(angle)+y*Math.cos(angle);
    assert.ok(screenX*dx+screenY*dy>0,'gaze points toward cursor after rotation');
    assert.ok(Math.abs(screenX*dy-screenY*dx)<.75,'gaze stays within one pixel of cursor direction');
    assert.ok(Math.hypot(x,y)<=8,'pupil travel remains bounded');
  }

  assertGaze(1,0);
  s.event(s.window,'pointermove',{clientX:-900,clientY:100});s.advance(20);
  assertGaze(-1,0);
  s.event(s.window,'pointermove',{clientX:200,clientY:900});s.advance(20);
  assertGaze(0,1);
  s.event(s.window,'resize');
  s.event(s.window,'pointermove',{clientX:900,clientY:100});
  const escaped=s.event(button,'keydown',{key:'Escape'});
  assert.equal(escaped.defaultPrevented,true,'Escape is captured even on the toggle');
  assert.equal(surface.style.filter,'contrast(.9)');
  assert.equal(button.getAttribute('aria-pressed'),'false');
  assert.equal(s.document.querySelector('.doodles-eyes-overlay').hidden,false,'closing stays visible until lids meet');
  s.advance(350);
  assert.equal(s.document.querySelector('.doodles-eyes-overlay').hidden,true);
  s.advance(700);
  assert.equal(surface.style.filter,'contrast(.9)','pending frames cannot reactivate distortion');
  assert.equal(s.event(s.window,'keydown',{key:'Escape'}).defaultPrevented,undefined,'Escape is left alone when inactive');
  button.click();s.advance(20);
  assert.equal(button.getAttribute('aria-pressed'),'true','eye mode can reopen after Escape');
  assertGaze(1,0);
  button.click();s.advance(350);assert.equal(surface.style.filter,'contrast(.9)');
  button.click();s.event(s.window,'pagehide');assert.equal(surface.style.filter,'contrast(.9)');
  s.event(s.window,'pointermove',{clientX:900,clientY:100});s.advance(40);
  assert.equal(s.document.querySelector('.doodles-eyes-overlay'),null);
});

